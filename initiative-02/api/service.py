import uuid
from datetime import datetime, timezone
from typing import List, Optional

from api.models import (
    AnomalyAlert,
    DetectionResult,
    EvaluationBatchRequest,
    EvaluationBatchResponse,
    TelemetryEvent,
)


class EvaluationService:
    def __init__(self):
        # Attempt to load detector and rule engine implementations if available
        self.detectors = []
        self.rule_engine = None

        try:
            from detectors import ZScoreDetector, TimeSeriesDetector  # type: ignore
            self.detectors.extend([ZScoreDetector(), TimeSeriesDetector()])
        except (ImportError, AttributeError):
            pass

        try:
            from rules import RuleEngine  # type: ignore
            self.rule_engine = RuleEngine()
        except (ImportError, AttributeError):
            pass

    def evaluate_event(self, event: TelemetryEvent) -> List[AnomalyAlert]:
        alerts: List[AnomalyAlert] = []

        # 1. Run detectors if available
        detections: List[DetectionResult] = []
        for detector in self.detectors:
            if hasattr(detector, "detect"):
                try:
                    res = detector.detect(event)
                    if isinstance(res, list):
                        detections.extend(res)
                except Exception:
                    pass

        # 2. Run rule engine if available
        if self.rule_engine and hasattr(self.rule_engine, "evaluate_all"):
            try:
                engine_alerts = self.rule_engine.evaluate_all(event, detections)
                if isinstance(engine_alerts, list):
                    alerts.extend(engine_alerts)
            except Exception:
                pass

        # 3. Fallback/Default heuristic rule evaluation if no alerts generated by rule engine
        if not alerts:
            default_alerts = self._evaluate_default_rules(event, detections)
            alerts.extend(default_alerts)

        return alerts

    def evaluate_batch(self, request: EvaluationBatchRequest) -> EvaluationBatchResponse:
        all_alerts: List[AnomalyAlert] = []
        for event in request.events:
            alerts = self.evaluate_event(event)
            all_alerts.extend(alerts)

        return EvaluationBatchResponse(
            processed_count=len(request.events),
            alerts=all_alerts,
        )

    def _evaluate_default_rules(
        self,
        event: TelemetryEvent,
        detections: List[DetectionResult],
    ) -> List[AnomalyAlert]:
        alerts: List[AnomalyAlert] = []
        metrics = event.metrics

        now_utc = datetime.now(timezone.utc)

        latency = metrics.latency_p99_ms or 0.0
        error_rate = metrics.error_rate_pct or 0.0
        cpu = metrics.cpu_usage_pct or 0.0
        memory = metrics.memory_rss_mb or 0.0

        if latency > 1000.0 and error_rate > 15.0:
            alerts.append(
                AnomalyAlert(
                    alert_id=f"alt_{uuid.uuid4().hex[:8]}",
                    detected_at_utc=now_utc,
                    source_event_ids=[event.event_id],
                    source_service=event.source_service,
                    anomaly_type="LATENCY_SPIKE_AND_ERROR_SURGE",
                    z_score=round(latency / 300.0, 2),
                    confidence=0.96,
                    recommended_severity="SEV-1",
                )
            )
        elif latency > 1000.0:
            alerts.append(
                AnomalyAlert(
                    alert_id=f"alt_{uuid.uuid4().hex[:8]}",
                    detected_at_utc=now_utc,
                    source_event_ids=[event.event_id],
                    source_service=event.source_service,
                    anomaly_type="LATENCY_SPIKE",
                    z_score=round(latency / 300.0, 2),
                    confidence=0.85,
                    recommended_severity="SEV-2",
                )
            )
        elif error_rate > 15.0:
            alerts.append(
                AnomalyAlert(
                    alert_id=f"alt_{uuid.uuid4().hex[:8]}",
                    detected_at_utc=now_utc,
                    source_event_ids=[event.event_id],
                    source_service=event.source_service,
                    anomaly_type="ERROR_RATE_SURGE",
                    z_score=round(error_rate / 5.0, 2),
                    confidence=0.85,
                    recommended_severity="SEV-2",
                )
            )
        elif cpu >= 90.0:
            alerts.append(
                AnomalyAlert(
                    alert_id=f"alt_{uuid.uuid4().hex[:8]}",
                    detected_at_utc=now_utc,
                    source_event_ids=[event.event_id],
                    source_service=event.source_service,
                    anomaly_type="HIGH_CPU_USAGE",
                    z_score=round((cpu - 50.0) / 10.0, 2),
                    confidence=0.80,
                    recommended_severity="SEV-3",
                )
            )
        elif memory >= 4096.0:
            alerts.append(
                AnomalyAlert(
                    alert_id=f"alt_{uuid.uuid4().hex[:8]}",
                    detected_at_utc=now_utc,
                    source_event_ids=[event.event_id],
                    source_service=event.source_service,
                    anomaly_type="HIGH_MEMORY_USAGE",
                    z_score=round(memory / 1000.0, 2),
                    confidence=0.80,
                    recommended_severity="SEV-3",
                )
            )

        return alerts
